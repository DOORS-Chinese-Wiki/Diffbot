FALLBACK_LANG = "en"


def get_message(lang: str, key: str, **kwargs: object) -> str:
    """按语言取模板并格式化；语言/键缺失时回退，最终返回键名。"""
    template = MESSAGES.get(lang, MESSAGES[FALLBACK_LANG]).get(key)
    if template is None:
        template = MESSAGES[FALLBACK_LANG].get(key, key)
    try:
        return template.format(**kwargs)
    except (KeyError, IndexError):
        return template
